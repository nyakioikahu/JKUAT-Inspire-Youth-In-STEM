#loops are essential part of programming. They allow you to repeat a block of code multiple times
#There are two types of loops in python, "for" and "while".

# "for" loop
#The "for" loop is used to iterate over a sequence (list,tuple,string) or other iterable objects
#Let us iterate over a list
fruits=["apple", "banana", "cherry", "pineapple"]   
#square brackets are used in lists

for fruit in fruits:
    print(fruit)  


for i in range (5):
   print(i)

for char in "nyakio":
    print(char)

